    pub fn is_fixed_mass(&self) -> bool {
        !matches!(
            self,
            Self::Rho0
                | Self::RhoPlus
                | Self::RhoMinus
                | Self::Omega
                | Self::Phi
                | Self::EtaPrime
                | Self::A0_980
                | Self::F0_980
                | Self::KStar892Zero
                | Self::KStar892Plus
                | Self::KStar892Minus
                | Self::AntiKStar892Zero
                | Self::K1Plus1400
                | Self::K1Minus1400
                | Self::B1Plus1235
                | Self::Sigma1385Minus
                | Self::Sigma1385Zero
                | Self::Sigma1385Plus
                | Self::EtaC
                | Self::ChiC0
                | Self::DeltaPlusPlus
        )
    }

    pub fn is_resonance(&self) -> bool {
        if self.is_fixed_mass() {
            return false;
        }
        !matches!(self, Self::UnknownParticle | Self::Phi | Self::Omega)
    }

