impl FromStr for Particle {
    type Err = crate::GlueXCoreError;

    fn from_str(name: &str) -> Result<Self, Self::Err> {
        Self::VARIANTS
            .iter()
            .copied()
            .find(|particle| particle.enum_name() == name)
            .ok_or_else(|| crate::GlueXCoreError::ParticleParse(name.to_owned()))
    }
}

